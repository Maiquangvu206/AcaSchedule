"""Provider chain: Gemini / OpenRouter ⇄ local fallback.

The order of providers is rotated per request, so load spreads across both
accounts. Within a provider, API keys are rotated by ``rotation.py``. If a
provider fails completely, the next provider is tried; if every provider fails,
the deterministic local answer is returned.
"""

from __future__ import annotations

import logging

from . import gemini, openrouter, runtime_config

logger = logging.getLogger(__name__)

_MODULES = {"gemini": gemini, "openrouter": openrouter}

_provider_cursor = 0


def reset_rotation_state() -> None:
    """Reset provider cursor and every provider's key rotation (used by tests)."""
    global _provider_cursor
    _provider_cursor = 0
    runtime_config.reset_runtime_config_cache()
    for module in _MODULES.values():
        module.reset_rotation_state()


def _is_configured(name: str, config: runtime_config.RuntimeConfig) -> bool:
    if name == "gemini":
        return bool(config.gemini_keys)
    if name == "openrouter":
        return bool(config.openrouter_keys)
    return False


async def _ordered_providers() -> list[str]:
    """Configured providers in rotation order (round-robin per request)."""
    global _provider_cursor

    config = await runtime_config.get_runtime_config()
    order = list(config.provider_order)
    usable = [name for name in order if _is_configured(name, config)] or order

    start = _provider_cursor % len(usable)
    _provider_cursor = (start + 1) % len(usable)
    return usable[start:] + usable[:start]


async def generate_with_provider(prompt: str) -> tuple[str, str]:
    """Ask the first healthy provider; return ``(text, provider_name)``.

    Raises only when every provider fails.
    """
    failures: list[str] = []

    for name in await _ordered_providers():
        module = _MODULES.get(name)
        if module is None:
            continue
        try:
            text = await module.generate(prompt)
        except Exception as exc:  # noqa: BLE001 - try the next provider
            logger.warning("AI provider %s failed: %s", name, exc)
            failures.append(f"{name}: {exc}")
            continue

        logger.info("AI answer generated by %s", name)
        return text, name

    raise RuntimeError("All AI providers failed — " + "; ".join(failures))


async def generate(prompt: str) -> str:
    """Return the answer text from the first healthy provider."""
    text, _ = await generate_with_provider(prompt)
    return text


async def generate_or_fallback(prompt: str, fallback: str) -> tuple[str, bool]:
    """Return provider output when possible, otherwise the local fallback.

    Never raises: an exhausted quota on every provider must degrade to the
    deterministic local answer instead of an HTTP error for the student.
    """

    try:
        return await generate(prompt), False
    except Exception as exc:  # noqa: BLE001
        logger.warning("All AI providers unavailable, using fallback answer: %s", exc)
        return fallback, True


async def generate_or_fallback_meta(
    prompt: str, fallback: str
) -> tuple[str, str, bool]:
    """Like ``generate_or_fallback`` but also reports which provider answered.

    Returns ``(text, model_name, used_fallback)`` where ``model_name`` is
    ``"gemini"``, ``"openrouter"`` or ``"fallback"``.
    """

    try:
        text, provider = await generate_with_provider(prompt)
        return text, provider, False
    except Exception as exc:  # noqa: BLE001
        logger.warning("All AI providers unavailable, using fallback answer: %s", exc)
        return fallback, "fallback", True
